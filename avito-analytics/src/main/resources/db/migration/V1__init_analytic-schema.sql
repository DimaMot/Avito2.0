CREATE TABLE item_view_stats
(
    item_id           BIGINT PRIMARY KEY,
    total_views       BIGINT      NOT NULL DEFAULT 0,
    unique_views      BIGINT      NOT NULL DEFAULT 0,
    last_viewed_at    TIMESTAMPTZ NOT NULL,
    views_last_7_days BIGINT      NOT NULL DEFAULT 0
);
CREATE INDEX idx_view_unique ON item_view_stats (unique_views DESC);
CREATE INDEX idx_view_last_7_days ON item_view_stats (views_last_7_days DESC);

CREATE TABLE item_view_stats_by_city
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id        BIGINT       NOT NULL,
    city           VARCHAR(100) NOT NULL,
    total_views    BIGINT       NOT NULL DEFAULT 0,
    last_viewed_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_item_city UNIQUE (item_id, city)
);
CREATE INDEX idx_view_cities_city ON item_view_stats_by_city (city);

CREATE TABLE item_views_daily
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL,
    day     DATE   NOT NULL,
    views   BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_item_day UNIQUE (item_id, day)
);
CREATE INDEX idx_view_daily_day ON item_views_daily (day);

CREATE TABLE item_search_city
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query          VARCHAR(255) NOT NULL,
    city           VARCHAR(100) NOT NULL,
    total_views    BIGINT       NOT NULL DEFAULT 0,
    results_count  INT          NOT NULL DEFAULT 0,
    last_search_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_search_city UNIQUE (query, city)
);
CREATE INDEX idx_search_cities_city ON item_search_city (city);

CREATE TABLE item_search_stats
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query          VARCHAR(255) NOT NULL,
    total_views    BIGINT       NOT NULL DEFAULT 0,
    results_count  INT          NOT NULL DEFAULT 0,
    unique_views   BIGINT       NOT NULL DEFAULT 0,
    last_search_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_search_query UNIQUE (query)
);
CREATE INDEX idx_search_stats_total_views ON item_search_stats (total_views DESC);
CREATE INDEX idx_search_stats_unique_views ON item_search_stats (unique_views DESC);